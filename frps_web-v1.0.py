def load_panel_config():
    """加载面板配置（用户名和密码哈希）"""
    default_config = {
        "username": WEB_API_USER,
        "password_hash": hashlib.sha256(WEB_API_PWD.encode()).hexdigest()
    }
    if os.path.exists(PANEL_CONFIG_FILE):
        try:
            with open(PANEL_CONFIG_FILE, 'r') as f:
                config = json.load(f)
                # 确保配置完整
                if "username" in config and "password_hash" in config:
                    return config
        except:
            pass
    # 如果文件不存在或损坏，创建默认配置
    save_panel_config(default_config)
    return default_config

def save_panel_config(config):
    """保存面板配置"""
    try:
        with open(PANEL_CONFIG_FILE, 'w') as f:
            json.dump(config, f)
        os.chmod(PANEL_CONFIG_FILE, 0o600)
    except Exception as e:
        print(f"Error saving panel config: {e}")

def check_session(session_id):
    """检查会话是否有效"""
    if not session_id or session_id not in SESSIONS:
        return False
    session = SESSIONS[session_id]
    if time.time() > session['expire_time']:
        del SESSIONS[session_id]
        return False
    return True

def create_session(username):
    """创建新会话"""
    session_id = ''.join(random.choices(string.ascii_letters + string.digits, k=32))
    SESSIONS[session_id] = {
        'user': username,
        'expire_time': time.time() + 86400 # 24小时过期
    }
    return session_id

def cleanup_sessions():
    """定期清理过期会话"""
    while True:
        now = time.time()
        expired = [sid for sid, s in SESSIONS.items() if s['expire_time'] < now]
        for sid in expired:
            del SESSIONS[sid]
        time.sleep(3600) # 每小时清理一次

