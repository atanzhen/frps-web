class FRPSHandler(BaseHTTPRequestHandler):
    def log_message(self, format, *args):
        pass

    def send_html(self, content):
        self.send_response(200)
        self.send_header('Content-type', 'text/html; charset=utf-8')
        self.end_headers()
        self.wfile.write(content.encode('utf-8'))

    def send_json(self, data):
        self.send_response(200)
        self.send_header('Content-type', 'application/json; charset=utf-8')
        self.end_headers()
        self.wfile.write(json.dumps(data).encode('utf-8'))

    def send_text(self, text):
        self.send_response(200)
        self.send_header('Content-type', 'text/plain; charset=utf-8')
        self.end_headers()
        self.wfile.write(text.encode('utf-8'))

    def get_session_from_post(self):
        """从POST数据中提取并验证session"""
        content_len = int(self.headers.get('Content-Length', 0))
        post_data = self.rfile.read(content_len)
        try:
            data = json.loads(post_data.decode('utf-8'))
            session_id = data.get('session_id')
            if check_session(session_id):
                return True, data, session_id
            return False, data, None
        except:
            return False, {}, None

    def do_GET(self):
        parsed = urllib.parse.urlparse(self.path)
        path = parsed.path
        
        if path == '/':
            options_html = ""
            for v in AVAILABLE_VERSIONS:
                options_html += '<option value="{0}">v{0}</option>\n'.format(v)
            
            py_ver = "{0}.{1}.{2}".format(sys.version_info.major, sys.version_info.minor, sys.version_info.micro)
            final_html = HTML_TEMPLATE.replace("{{VERSION_OPTIONS}}", options_html).replace("{{PY_VERSION}}", py_ver)
            self.send_html(final_html)
        else:
            self.send_response(404)
            self.end_headers()

    def do_POST(self):
        parsed = urllib.parse.urlparse(self.path)
        path = parsed.path
        
        # 公开接口：登录
        if path == '/api/login':
            content_len = int(self.headers.get('Content-Length', 0))
            post_data = self.rfile.read(content_len)
            try:
                data = json.loads(post_data.decode('utf-8'))
                username = data.get('username')
                password = data.get('password')
                
                panel_config = load_panel_config()
                pwd_hash = hashlib.sha256(password.encode()).hexdigest()
                
                if username == panel_config['username'] and pwd_hash == panel_config['password_hash']:
                    session_id = create_session(username)
                    self.send_json({'success': True, 'session_id': session_id})
                else:
                    self.send_json({'success': False, 'msg': '用户名或密码错误'})
            except Exception as e:
                self.send_json({'success': False, 'msg': '请求格式错误'})
            return

        # 公开接口：检查会话
        if path == '/api/check_session':
            valid, data, session_id = self.get_session_from_post()
            self.send_json({'valid': valid})
            return

        # 公开接口：退出
        if path == '/api/logout':
            valid, data, session_id = self.get_session_from_post()
            if valid and session_id:
                if session_id in SESSIONS:
                    del SESSIONS[session_id]
            self.send_json({'success': True})
            return

        # 公开接口：修改密码
        if path == '/api/change_password':
            valid, data, session_id = self.get_session_from_post()
            if not valid:
                self.send_json({'success': False, 'valid': False, 'msg': '未登录或会话过期'})
                return
            
            old_pwd = data.get('old_password')
            new_pwd = data.get('new_password')
            
            panel_config = load_panel_config()
            old_pwd_hash = hashlib.sha256(old_pwd.encode()).hexdigest()
            
            if old_pwd_hash != panel_config['password_hash']:
                self.send_json({'success': False, 'msg': '原密码错误'})
                return
            
            # 更新密码
            new_pwd_hash = hashlib.sha256(new_pwd.encode()).hexdigest()
            panel_config['password_hash'] = new_pwd_hash
            save_panel_config(panel_config)
            
            # 使当前会话失效（强制重新登录）
            if session_id in SESSIONS:
                del SESSIONS[session_id]
                
            self.send_json({'success': True, 'msg': '密码修改成功'})
            return

        # 以下接口需要登录验证
        valid, data, session_id = self.get_session_from_post()
        if not valid:
            self.send_json({'success': False, 'valid': False, 'msg': '未登录或会话过期'})
            return

        if path == '/api/status':
            self.send_json({
                'valid': True,
                'ip': get_ip(),
                'arch': get_arch(),
                'version': get_installed_version(),
                'is_installed': is_installed(),
                'status': get_service_status(),
                'config': read_config()
            })
        elif path == '/api/traffic':
            t_in, t_out = get_traffic_stats()
            self.send_json({'valid': True, 'total_in': t_in, 'total_out': t_out})
        elif path == '/api/logs':
            logs = ""
            if os.path.exists(LOG_FILE):
                try:
                    with open(LOG_FILE, 'r', encoding='utf-8') as f:
                        lines = f.readlines()
                        logs = "".join(lines[-50:])
                except: pass
            self.send_text(logs)
        elif path == '/api/frps_logs':
            self.send_text(get_frps_logs())
        elif path == '/api/install':
            version = data.get('version', '').strip()
            mode = data.get('mode')
            
            if not version:
                self.send_json({'success': False, 'valid': True, 'msg': '未选择版本'})
                return

            log_operation('INSTALL', '版本 {0} ({1})'.format(version, mode), 'START')
            
            old_config = None
            if mode == 'keep':
                old_config = read_config()
            
            if mode == 'reset' or mode == 'new':
                if os.path.exists(CONFIG_FILE): os.remove(CONFIG_FILE)
                run_cmd([get_sysctl_path(), "stop", SERVICE_NAME])
                bin_path = os.path.join(INSTALL_DIR, "frps")
                if os.path.exists(bin_path): os.remove(bin_path)
            else:
                run_cmd([get_sysctl_path(), "stop", SERVICE_NAME])
                bin_path = os.path.join(INSTALL_DIR, "frps")
                if os.path.exists(bin_path): os.remove(bin_path)

            success, msg = download_and_install(version)
            if not success:
                log_operation('INSTALL', '版本 ' + version, 'FAILED')
                self.send_json({'success': False, 'valid': True, 'msg': msg})
                return

            if mode == 'reset' or mode == 'new':
                token = ''.join(random.choice(string.ascii_letters + string.digits) for _ in range(32))
                write_config('7000', '18080', '18443', token)
            elif old_config:
                write_config(old_config['bindPort'], old_config['vhostHTTPPort'], old_config['vhostHTTPSPort'], old_config['token'])
            
            setup_systemd()
            
            success, msg = control_service('restart')
            log_operation('INSTALL', '版本 ' + version, 'SUCCESS' if success else 'FAILED')
            
            new_version = get_installed_version() or "未知版本"
            if success:
                if mode == 'new': final_msg = "全新安装完成，当前版本: v{0}".format(new_version)
                elif mode == 'keep': final_msg = "保留配置重装完成，当前版本: v{0}".format(new_version)
                elif mode == 'reset': final_msg = "清除配置重装完成，当前版本: v{0}".format(new_version)
                else: final_msg = "安装完成，当前版本: v{0}".format(new_version)
            else:
                final_msg = "文件安装成功(v{0})，但服务启动失败: {1}".format(new_version, msg)
                
            self.send_json({'success': success, 'valid': True, 'msg': final_msg})

        elif path == '/api/config':
            bind_port = data.get('bind_port')
            http_port = data.get('http_port')
            https_port = data.get('https_port')
            token = data.get('token')

            log_operation('CONFIG', '更新端口与Token', 'START')
            
            if os.path.exists(CONFIG_FILE):
                shutil.copy(CONFIG_FILE, CONFIG_FILE + '.bak')
            
            write_config(bind_port, http_port, https_port, token)
            success, msg = control_service('restart')
            
            if not success:
                if os.path.exists(CONFIG_FILE + '.bak'):
                    shutil.copy(CONFIG_FILE + '.bak', CONFIG_FILE)
                    control_service('restart')
                log_operation('CONFIG', '更新端口与Token', 'ROLLBACK')
                self.send_json({'success': False, 'valid': True, 'msg': '配置应用失败，已回滚。原因: ' + msg})
            else:
                log_operation('CONFIG', '更新端口与Token', 'SUCCESS')
                self.send_json({'success': True, 'valid': True, 'msg': '配置更新并重启成功'})

        elif path == '/api/service':
            action = data.get('action')
            action_cn = {'start': '启动', 'stop': '停止', 'restart': '重启', 'uninstall': '卸载'}.get(action, action)
            
            if action not in ['start', 'stop', 'restart', 'uninstall']:
                self.send_json({'success': False, 'valid': True, 'msg': '无效操作'})
                return
            
            log_operation('SERVICE', action_cn + '服务', 'START')
            success, msg = control_service(action)
            log_operation('SERVICE', action_cn + '服务', 'SUCCESS' if success else 'FAILED')
            self.send_json({'success': success, 'valid': True, 'msg': msg})
        else:
            self.send_response(404)
            self.end_headers()

