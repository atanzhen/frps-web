def log_operation(action, detail, status):
    action_map = {
        'INSTALL': '安装/重装',
        'CONFIG': '修改配置',
        'SERVICE': '服务控制'
    }
    status_map = {
        'START': '开始执行',
        'SUCCESS': '执行成功',
        'FAILED': '执行失败',
        'ROLLBACK': '配置已回滚'
    }
    cn_action = action_map.get(action, action)
    cn_status = status_map.get(status, status)
    
    try:
        with open(LOG_FILE, 'a', encoding='utf-8') as f:
            f.write("[{0}] {1} | {2} | {3}\n".format(
                datetime.now().strftime('%Y-%m-%d %H:%M:%S'), cn_action, detail, cn_status))
    except:
        pass

def run_cmd(cmd, shell=False):
    try:
        p = subprocess.Popen(cmd, shell=shell, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        out, err = p.communicate()
        return p.returncode, out.decode('utf-8', errors='ignore'), err.decode('utf-8', errors='ignore')
    except Exception as e:
        return -1, "", str(e)

def get_arch():
    try:
        code, out, _ = run_cmd(["uname", "-m"])
        machine = out.strip()
        arch_map = {
            "x86_64": "amd64", "amd64": "amd64",
            "aarch64": "arm64", "arm64": "arm64",
            "armv7l": "arm", "armv6l": "arm",
            "i386": "386", "i686": "386"
        }
        return arch_map.get(machine, machine)
    except:
        return "amd64"

def get_ip():
    try:
        code, out, _ = run_cmd(["ip", "route", "get", "8.8.8.8"])
        if code == 0:
            m = re.search(r'src\s+([0-9.]+)', out)
            if m: return m.group(1)
    except: pass
    try:
        code, out, _ = run_cmd(["hostname", "-I"])
        if code == 0: return out.strip().split()[0]
    except: pass
    return "127.0.0.1"

def get_installed_version():
    bin_path = os.path.join(INSTALL_DIR, "frps")
    if os.path.exists(bin_path) and os.access(bin_path, os.X_OK):
        try:
            code, out, _ = run_cmd([bin_path, "--version"])
            if code == 0:
                parts = out.strip().split()
                for part in parts:
                    if re.match(r'^\d+\.\d+', part):
                        return part
                return out.strip().split('\n')[0]
        except:
            pass
    return None

def is_installed():
    return get_installed_version() is not None

def get_sysctl_path():
    if os.path.exists("/bin/systemctl"): return "/bin/systemctl"
    if os.path.exists("/usr/bin/systemctl"): return "/usr/bin/systemctl"
    return "systemctl"

def get_service_status():
    sysctl = get_sysctl_path()
    code, out, _ = run_cmd([sysctl, "is-active", SERVICE_NAME])
    return out.strip() if code == 0 else "inactive"

def read_config():
    config = {'bindPort': '7000', 'vhostHTTPPort': '18080', 'vhostHTTPSPort': '18443', 'token': ''}
    if os.path.exists(CONFIG_FILE):
        try:
            with open(CONFIG_FILE, 'r', encoding='utf-8') as f:
                content = f.read()
                m = re.search(r'bindPort\s*=\s*(\d+)', content)
                if m: config['bindPort'] = m.group(1)
                m = re.search(r'vhostHTTPPort\s*=\s*(\d+)', content)
                if m: config['vhostHTTPPort'] = m.group(1)
                m = re.search(r'vhostHTTPSPort\s*=\s*(\d+)', content)
                if m: config['vhostHTTPSPort'] = m.group(1)
                m = re.search(r'(?:auth\.)?token\s*=\s*"([^"]+)"', content)
                if m: config['token'] = m.group(1)
        except: pass
    return config

